r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 5 "Серия 1.3: da3m0ns", урок 5.1 "Тихий перегрев", шаг 8

Напишите мониторинг температуры в хранилище, который ловит и превышение предела, и тихий рост, как в
плане Эллиота.

Ввод: в первой строке три целых числа: `limit` (предельная температура), `k` и `d` (тревога по
тренду). Во второй строке показания датчика раз в час (целые числа через пробел).

Вывод: первая тревога, если она есть. Просматривайте часы по порядку и для каждого проверяйте:
- если показание больше `limit`, выведите `час i: превышен предел`;
- иначе если с часа `i` можно отсчитать `k` часов назад и показание выросло за это время хотя бы на
  `d`, выведите `час i: рост на X за k ч`, где `X` означает величину роста.

Часы нумеруются с единицы. Если тревог нет, выведите `норма`.

Пример ввода:
    30 3 4
    20 21 20 21 22 21

Пример вывода:
    норма
"""

limit, k, d = map(int, input().split())
readings = list(map(int, input().split()))
alarm = "норма"
for i, t in enumerate(readings):
    if t > limit:
        alarm = f"час {i + 1}: превышен предел"
        break
    if i >= k and t - readings[i - k] >= d:
        alarm = f"час {i + 1}: рост на {t - readings[i - k]} за {k} ч"
        break
print(alarm)
