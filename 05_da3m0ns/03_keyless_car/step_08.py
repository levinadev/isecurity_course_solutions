r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 5 "Серия 1.3: da3m0ns", урок 5.3 "Машина без ключа", шаг 8

Напишите модель проверки плавающего кода на стороне машины. Для простоты код брелока равен просто
значению счётчика. В настоящих брелоках оно ещё и зашифровано.

Машина хранит свой счётчик `counter` и ширину окна `window`. Для каждого полученного кода `code`:
- если `code` не больше `counter`, выведите `отказ: повтор`;
- иначе если `code` больше `counter + window`, выведите `отказ: вне окна`;
- иначе выведите `открыто` и запомните `code` как новое значение счётчика.

Ввод: в первой строке `counter` и `window`, во второй число кодов `n`, дальше `n` строк по одному
коду.

Вывод: `n` строк с решением по каждому коду.

Пример ввода:
    100 16
    3
    101
    102
    102

Пример вывода:
    открыто
    открыто
    отказ: повтор
"""

counter, window = map(int, input().split())
n = int(input())
for _ in range(n):
    code = int(input())
    if code <= counter:
        print("отказ: повтор")
    elif code > counter + window:
        print("отказ: вне окна")
    else:
        counter = code
        print("открыто")
