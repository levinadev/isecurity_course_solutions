r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 7 "Серия 1.5: br4ve-trave1er", урок 7.1 "Флешка на парковке", шаг 7

Напишите проверку флешки: программа получает список файлов и отмечает потенциально опасные.

Опасными считайте файлы, у которых последнее расширение входит в набор: `exe, scr, bat, cmd, com,
pif, lnk, js, vbs`. Регистр не важен: `.EXE` и `.exe` считаются одним расширением. Расширение: часть
имени после последней точки; если точек в имени нет, расширения нет.

Ввод: в первой строке число файлов `n`, дальше `n` строк с именами.

Вывод: для каждого опасного файла в порядке ввода строка `имя: опасное расширение .ext`. Если в
имени две или больше точек, а последнее расширение входит в список `exe, scr, bat, cmd, com, pif`,
добавьте в конец ` под видом документа`. Если опасных файлов нет, выведите `подозрительных файлов
нет`.

Пример ввода:
    4
    отчёт.pdf
    фото.jpg
    зарплаты.xlsx.exe
    readme.txt

Пример вывода:
    зарплаты.xlsx.exe: опасное расширение .exe под видом документа
"""

DANGEROUS = {"exe", "scr", "bat", "cmd", "com", "pif", "lnk", "js", "vbs"}
n = int(input())
flagged = []
for _ in range(n):
    name = input()
    parts = name.lower().rsplit(".", 1)
    ext = parts[1] if len(parts) == 2 else ""
    double = name.lower().count(".") >= 2 and ext in {"exe", "scr", "bat", "cmd", "com", "pif"}
    if ext in DANGEROUS:
        flagged.append(f"{name}: опасное расширение .{ext}" + (" под видом документа" if double else ""))
print("\n".join(flagged) if flagged else "подозрительных файлов нет")
