r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 2 "Серия 1.0: hellofriend", урок 2.4 "DDoS как дымовая завеса", шаг 8

Напишите программу, которая находит в журнале веб-сервера адреса, отправившие подозрительно много
запросов. Так ловят бота или подбор пароля с одного адреса. Крупный DDoS идёт с тысяч адресов, и его
так не остановить, но и при разборе атаки полезно знать, кто шумит больше всех.

Ввод: в первой строке два целых числа через пробел: `m` (число записей в журнале) и `t` (порог).
Дальше `m` строк, в каждой IP-адрес, с которого пришёл запрос.

Вывод: адреса, от которых пришло больше `t` запросов, по одному в строке в формате `адрес запросов:
число`, например `10.0.0.1 запросов: 3`. Сначала адреса с наибольшим числом запросов; при равенстве
в алфавитном порядке адресов (как сравнивает строки Python). Если таких адресов нет, выведите `нет`.

Пример ввода:
    5 2
    10.0.0.1
    10.0.0.2
    10.0.0.1
    10.0.0.3
    10.0.0.1

Пример вывода:
    10.0.0.1 запросов: 3
"""

m, t = map(int, input().split())
counts = {}
for _ in range(m):
    ip = input().strip()
    counts[ip] = counts.get(ip, 0) + 1
heavy = [(ip, n) for ip, n in counts.items() if n > t]
heavy.sort(key=lambda item: (-item[1], item[0]))
if heavy:
    for ip, n in heavy:
        print(ip, "запросов:", n)
else:
    print("нет")
