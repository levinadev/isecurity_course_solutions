r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 2 "Серия 1.0: hellofriend", урок 2.1 "Пароль Кристы", шаг 9

Напишите проверку пароля, которая ловит ошибку Кристы, пароль из фактов о человеке, и ещё две явные
слабости: короткий пароль и пароль из повторов.

Ввод: в первой строке пароль, во второй через пробел слова о владельце, например имена, любимые
группы, клички, годы.

Вывод: по одному замечанию в строке, в таком порядке:
- если пароль короче 15 символов, выведите `короче 15 символов`;
- если в пароле меньше 5 разных символов, выведите `мало разных символов`;
- для каждого слова в порядке ввода: если слово встречается в пароле, выведите `содержит: слово`,
  иначе если в пароле встречается это слово задом наперёд, выведите `содержит наоборот: слово`.

Регистр букв не учитывайте нигде: `DYLAN` и `dylan` считаются одним и тем же словом, `A` и `a` одним
символом. Слово в замечании выводите так, как оно записано во второй строке. Если замечаний нет,
выведите `OK`.

Такая проверка ловит только самые явные ошибки. Полные требования к паролям описаны в стандарте NIST
SP 800-63B, о котором шла речь в уроке: длина, допустимые символы, сверка со списками популярных и
утёкших паролей.

Пример ввода:
    Dylan_2791
    Криста Dylan 1972

Пример вывода:
    короче 15 символов
    содержит: Dylan
    содержит наоборот: 1972
"""

password = input()
words = input().split()
low = password.lower()
notes = []
if len(password) < 15:
    notes.append("короче 15 символов")
if len(set(low)) < 5:
    notes.append("мало разных символов")
for word in words:
    w = word.lower()
    if w in low:
        notes.append(f"содержит: {word}")
    elif w[::-1] in low:
        notes.append(f"содержит наоборот: {word}")
print("\n".join(notes) if notes else "OK")
