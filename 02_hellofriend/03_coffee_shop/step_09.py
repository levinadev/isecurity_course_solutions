r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 2 "Серия 1.0: hellofriend", урок 2.3 "Секрет владельца кофейни", шаг 9

Учебная модель "луковой" маршрутизации. Настоящий Tor использует стойкие шифры, а здесь каждый слой
задаётся простым сдвигом букв по алфавиту, как в шифре Цезаря.

Отправитель зашифровал сообщение тремя слоями. Каждый узел снимает свой слой: сдвигает каждую
латинскую букву назад по алфавиту на свой ключ, то есть на столько шагов, сколько в ключе. Пробелы
не меняются. Узлы работают по очереди: входной, средний, выходной.

Латинский алфавит: `abcdefghijklmnopqrstuvwxyz`. Например, сдвиг назад на 2: `l, k, j`, то есть `l`
становится `j`. Алфавит закольцован: после `a` снова идёт `z`, поэтому `b` со сдвигом назад на 3
становится `y` (`b, a, z, y`).

Ввод: в первой строке зашифрованное сообщение из строчных латинских букв и пробелов, во второй три
ключа узлов через пробел (целые числа от 0 до 25) в порядке "входной, средний, выходной".

Вывод: три строки с тем, что видит каждый узел после снятия своего слоя, в формате `входной: ...`,
`средний: ...`, `выходной: ...`.

Пример ввода:
    mjqqt
    1 2 2

Пример вывода:
    входной: lipps
    средний: jgnnq
    выходной: hello
"""

alphabet = "abcdefghijklmnopqrstuvwxyz"
message = input()
keys = input().split()
names = ["входной", "средний", "выходной"]
for i in range(3):
    key = int(keys[i])
    result = ""
    for ch in message:
        if ch == " ":
            result += " "
        else:
            number = alphabet.index(ch)
            result += alphabet[(number - key) % 26]
    message = result
    print(f"{names[i]}: {message}")
