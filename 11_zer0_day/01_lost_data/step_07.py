r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 11 "Серия 1.9: zer0-day", урок 11.1 "Данные, которые не вернуть", шаг 7

Напишите проверку резервного хранилища по правилу 3-2-1.

Ввод: в первой строке число копий `n`, дальше `n` строк вида `носитель место`, где `место` равно
`здесь` (в офисе) или `вне` (в другом месте).

Вывод: три строки о выполнении каждого пункта, в формате `3: ok` или `3: нет`:
- `3`: копий хотя бы три;
- `2`: использованы хотя бы два разных носителя;
- `1`: хотя бы одна копия хранится `вне`.

После трёх строк выведите `правило 3-2-1 соблюдено`, если выполнены все три пункта, иначе `правило
3-2-1 нарушено`.

Пример ввода:
    3
    диск здесь
    диск здесь
    облако вне

Пример вывода:
    3: ok
    2: ok
    1: ok
    правило 3-2-1 соблюдено
"""

n = int(input())
media = set()
offsite = False
for _ in range(n):
    name, place = input().split()
    media.add(name)
    if place == "вне":
        offsite = True
r3 = n >= 3
r2 = len(media) >= 2
r1 = offsite
print(f"3: {'ok' if r3 else 'нет'}")
print(f"2: {'ok' if r2 else 'нет'}")
print(f"1: {'ok' if r1 else 'нет'}")
print("правило 3-2-1 соблюдено" if r3 and r2 and r1 else "правило 3-2-1 нарушено")
