r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 11 "Серия 1.9: zer0-day", урок 11.2 "Уничтожение данных", шаг 7

После затирания диск проверяют: на экране HDShredder для этого есть счётчик ошибок проверки.
Напишите проверку: программа получает содержимое блоков диска и находит блоки, где остались данные.

Каждый блок записан в шестнадцатеричном виде. Блок считается затёртым, если он состоит только из
нулей (`0`) или только из `f`: так выглядит стёртая флеш-память. Регистр букв не важен: `FF` и `ff`
считаются одинаковыми.

Ввод: в первой строке число блоков `n`, дальше `n` строк с содержимым блоков.

Вывод: если все блоки затёрты, выведите `диск затёрт полностью`. Иначе выведите две строки: `не
затёрто блоков: k из n` и `блоки:` с номерами незатёртых блоков через пробел (нумерация с единицы).

Пример ввода:
    3
    00000000
    00000000
    00000000

Пример вывода:
    диск затёрт полностью
"""

n = int(input())
left = []
for i in range(1, n + 1):
    block = input().lower()
    if set(block) != {"0"} and set(block) != {"f"}:
        left.append(i)
if left:
    print(f"не затёрто блоков: {len(left)} из {n}")
    print("блоки:", *left)
else:
    print("диск затёрт полностью")
