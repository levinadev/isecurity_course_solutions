r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 10 "Серия 1.8: m1rr0r1ng", урок 10.1 "Зачем шифруют данные", шаг 9

Покажите на модели, почему короткий ключ опасен. Сообщение зашифровано шифром сдвига: каждую
латинскую заглавную букву сдвинули вперёд на неизвестный ключ от 0 до 25 (буквы идут по кругу: после
`Z` снова `A`). Пробелы не менялись.

Вы знаете одно слово, которое точно есть в исходном тексте. Переберите все 26 ключей и найдите тот,
при котором в расшифровке встречается это слово.

Ввод: в первой строке зашифрованный текст (заглавные латинские буквы и пробелы), во второй известное
слово (заглавными).

Вывод: найденный ключ и расшифрованный текст в формате `ключ: текст`. Если подходящих ключей
несколько, возьмите наименьший. Если ни один не подошёл, выведите `ключ не найден`.

Пример ввода:
    DWWDFN DW GDZQ
    DAWN

Пример вывода:
    3: ATTACK AT DAWN
"""

alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
cipher = input()
crib = input()
found = False
for key in range(26):
    plain = ""
    for ch in cipher:
        if ch == " ":
            plain += " "
        else:
            plain += alphabet[(alphabet.index(ch) - key) % 26]
    if crib in plain.split():
        print(f"{key}: {plain}")
        found = True
        break
if not found:
    print("ключ не найден")
