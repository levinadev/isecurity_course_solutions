r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 3 "Серия 1.1: ones-and-zer0es", урок 3.1 "Устаревший сервер и пароли", шаг 9

Напишите проверку входа. В базе хранится соль и хеш SHA-256 от строки "соль + пароль" в
шестнадцатеричном виде.

Ввод: в первой строке соль и сохранённый хеш через пробел. Во второй число `n`, дальше `n` строк с
паролями, которые вводили при попытках входа.

Вывод: для каждой попытки `вход разрешён` или `неверный пароль`. Хеш строки считается так:
`hashlib.sha256(text.encode()).hexdigest()`.

Пример ввода:
    x7Kq 553c93bd427baf8bcb5a316311c7d1efe0f6f40486d5ae2d7241049b470a1910
    3
    dylan_2791
    Dylan_2791
    Dylan_1972

Пример вывода:
    неверный пароль
    вход разрешён
    неверный пароль
"""

import hashlib

salt, stored = input().split()
n = int(input())
for _ in range(n):
    password = input()
    if hashlib.sha256((salt + password).encode()).hexdigest() == stored:
        print("вход разрешён")
    else:
        print("неверный пароль")
