r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 3 "Серия 1.1: ones-and-zer0es", урок 3.3 "Диск от незнакомца", шаг 6

Напишите проверку журнала камеры: найдите программы, которые обращались к камере без разрешения.

Ввод: в первой строке число записей `n`, дальше `n` строк вида `ЧЧ:ММ программа` в порядке времени.
Затем число `k` и `k` строк с именами программ, которым камера разрешена. Регистр в именах не важен:
`Zoom` и `zoom` считаются одной программой.

Вывод: для каждой неразрешённой программы в порядке первого обращения строка `программа: обращений
N, первое в ЧЧ:ММ`. Имя программы выводите так, как оно записано в её первом обращении. Если таких
программ нет, выведите `посторонних обращений нет`.

Пример ввода:
    4
    18:17 cdplayer
    18:20 zoom
    18:25 cdplayer
    18:40 cdplayer
    1
    zoom

Пример вывода:
    cdplayer: обращений 3, первое в 18:17
"""

n = int(input())
log = [input().split() for _ in range(n)]
k = int(input())
allowed = {input().lower() for _ in range(k)}
found = {}
for time, app in log:
    key = app.lower()
    if key in allowed:
        continue
    if key not in found:
        found[key] = [app, time, 0]
    found[key][2] += 1
if found:
    for app, time, count in found.values():
        print(f"{app}: обращений {count}, первое в {time}")
else:
    print("посторонних обращений нет")
