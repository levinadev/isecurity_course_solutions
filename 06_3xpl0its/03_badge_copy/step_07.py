r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 6 "Серия 1.4: 3xpl0its", урок 6.3 "Копия пропуска", шаг 7

Найдите аномалии в журнале проходов серверной за день.

Ввод: в первой строке число событий `n`, дальше `n` строк в порядке времени: `ВХОД имя` или `ВЫХОД
имя`. Имя может состоять из нескольких слов.

Вывод:
- для каждого события `ВЫХОД` человека, который по журналу не находился внутри, строка `без входа:
  имя`, в порядке событий;
- затем для каждого, кто к концу дня остался внутри, строка `остался: имя`, по алфавиту.

Повторный `ВХОД` того, кто уже внутри, ничего не меняет. Если аномалий нет, выведите `нарушений
нет`.

Пример ввода:
    4
    ВХОД Билл
    ВЫХОД Билл
    ВХОД Лора
    ВЫХОД Лора

Пример вывода:
    нарушений нет
"""

n = int(input())
inside = set()
problems = []
for _ in range(n):
    action, name = input().split(maxsplit=1)
    if action == "ВХОД":
        inside.add(name)
    elif name in inside:
        inside.discard(name)
    else:
        problems.append(f"без входа: {name}")
problems += [f"остался: {name}" for name in sorted(inside)]
print("\n".join(problems) if problems else "нарушений нет")
