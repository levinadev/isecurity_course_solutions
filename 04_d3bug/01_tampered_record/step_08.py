r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 4 "Серия 1.2: d3bug", урок 4.1 "Подменённый анализ", шаг 8

Проверьте журнал больницы, защищённый цепочкой хешей.

Хеш строки `i` считается как SHA-256 от строки "хеш строки `i-1` + запись строки `i`" в
шестнадцатеричном виде. Перед первой строкой "предыдущим хешем" считается строка из 64 нулей.

Ввод: в первой строке число записей `n`, дальше `n` строк вида `хеш запись`. Хеш стоит первым словом
строки, запись занимает всё остальное (в ней могут быть пробелы).

Вывод: `журнал цел`, если все хеши сходятся, иначе `нарушена строка i`, где `i` означает номер
первой строки (с единицы), хеш которой не совпал с пересчитанным. Для следующей строки берите в
качестве предыдущего хеша тот, что записан в журнале.

Хеш строки считается так: `hashlib.sha256(text.encode()).hexdigest()`.

Пример ввода:
    4
    066510e2ede2eb19cbf8fcb055d17819573d5cdc3aea8bf2fe5a58f353552cf9 пациент 114: анализ отрицательный
    5b64e9b5818f5688edf0ea4e26c55e0852dd27566c68d4ed00cf78933e12d300 пациент 115: анализ положительный
    655c7c85157362aaa13cb8492cd6a1a29c40e2107db754fd7332b275a12fc055 пациент 116: выписан
    d1701c6f4a9a31223885b6e1dfa132deae34860a14d9c7218d53f3d39911222e пациент 117: назначена терапия

Пример вывода:
    журнал цел
"""

import hashlib

n = int(input())
prev = "0" * 64
broken = 0
for i in range(1, n + 1):
    stored, record = input().split(" ", 1)
    expected = hashlib.sha256((prev + record).encode()).hexdigest()
    if expected != stored and not broken:
        broken = i
    prev = stored
print(f"нарушена строка {broken}" if broken else "журнал цел")
