r"""
Курс ИБ на примерах из "Мистера Робота"
Модуль 9 "Серия 1.7: wh1ter0se", урок 9.1 "Приманка", шаг 7

Напишите разбор журнала приманок. Есть список систем-приманок; к ним по работе никто не обращается.

Ввод: в первой строке имена приманок через пробел. Во второй число обращений `n`. Дальше `n` строк
вида `пользователь система` в порядке времени.

Вывод: для каждого обращения к приманке строка `тревога: пользователь -> система`, в порядке
времени. В самом конце строка `подозрительных пользователей: k`, где `k` означает число различных
пользователей, обращавшихся к приманкам. Если обращений к приманкам не было, вместо строк с
тревогами ничего не выводите, а в последней строке будет `подозрительных пользователей: 0`.

Пример ввода:
    trap01
    3
    anna web01
    boris trap01
    anna db01

Пример вывода:
    тревога: boris -> trap01
    подозрительных пользователей: 1
"""

honeys = set(input().split())
n = int(input())
suspects = set()
for _ in range(n):
    user, system = input().split()
    if system in honeys:
        print(f"тревога: {user} -> {system}")
        suspects.add(user)
print(f"подозрительных пользователей: {len(suspects)}")
